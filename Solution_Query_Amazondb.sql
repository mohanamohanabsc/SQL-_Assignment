
USE amazon_db;
-- 1) List all customers who have made purchases of more than $80
SELECT users.user_id, users.Name
FROM Users
INNER JOIN orders ON users.user_id=orders.user_id
where orders.total_amount>80;

-- 2)Retrieve all orders placed in the last 30 days along with the customer name and email.
SELECT orders.order_id, orders.order_date,users.Name, users.email, orders.total_amount
from orders
INNER JOIN users
ON orders.user_id=users.user_id
WHERE orders.order_date >= DATE_SUB(CURDATE(),INTERVAL 1000 DAY);

-- 3) Find the average product price for each category.

SELECT category, AVG(price) as avg_price
FROM products
GROUP BY category;

-- 4. List all customers who have purchased a product from the category Electronics.
SELECT users.User_id, users.email
FROM users
INNER JOIN orders on users.user_id=orders.user_id
INNER JOIN orderdetails on orders.order_id=orderdetails.order_id
INNER JOIN products on orderdetails.product_id=products.product_id
WHERE products.category='electronics';

-- 5.Find the total number of products sold and the total revenue generated for each product.
SELECT
    products.product_id,
    products.name as product_name,
    SUM(orderDetails.quantity) as total_quantity_sold,
    sum(orderDetails.quantity * products.price) as total_revenus
FROM  orderdetails
INNER JOIN products on orderdetails.product_id=products.product_id
GROUP BY products.product_id;

